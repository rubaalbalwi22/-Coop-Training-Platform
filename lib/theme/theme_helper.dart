/// Class containing the supported color schemes.
class ColorSchemes {
  static final primaryColorScheme = ColorScheme.light(
    // Primary colors
    primary: Color(0XFF8417F4),
    secondaryContainer:Colors.white,
     secondary:Color(0XFF8417F4),
    // On colors(text colors)
    onPrimary: Colors.white,//Color(0XFF230B41),
    onPrimaryContainer: Colors.white ,//Color(0XFFFFF3F4),
  );


}

